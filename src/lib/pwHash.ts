// 이제 「sha256:」 + SHA-256(로그 id + 비밀번호) 만 저장한다 — 로그마다 소금(id)이 달라서
// 인터넷의 해시 사전(레인보우 테이블)으로는 풀 수 없다. 다만 서버가 없는 구조라 짧은 비밀번호를
// 하나하나 대입해 보는 공격까지 막지는 못한다 — 본문 자체는 서버 규칙(회원만)으로 막는다.
// 새 파일로 따로 둔 이유: 원작 저장소 업데이트(Sync fork)와 충돌하지 않게.

